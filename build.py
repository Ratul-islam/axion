#!/usr/bin/env python3
"""Build the Axion Bangladesh site.

Every page shares one layout (preloader, header, menus, footer, setup finder,
equipment list), so the HTML lives in two places:

    src/layout.html      the shared page shell, with {{main}} where page content goes
    src/pages/*.html     one file per page: a small header block, then the page content

Running `python3 build.py` writes each page to its own folder so links stay clean
(`/equipment/` rather than `/equipment.html`):

    src/pages/home.html      ->  index.html
    src/pages/equipment.html ->  equipment/index.html
    ...

Edit the files in src/, then rebuild. The generated index.html files say so at the top.

Placeholders available in the layout and pages:
    {{root}}         relative path back to the site root ("./" or "../"), so the site
                     also works when hosted in a sub-folder
    {{title}}, {{description}}, {{page}}
Links in the layout marked data-nav="<nav value>" get aria-current="page" on that page.
"""

import pathlib
import re

SITE = pathlib.Path(__file__).resolve().parent
SRC = SITE / 'src'
FRONT_MATTER = re.compile(r'\A<!--\n(.*?)\n-->\n', re.S)


def read_page(path):
    text = path.read_text(encoding='utf-8')
    match = FRONT_MATTER.match(text)
    if not match:
        raise SystemExit(f'{path}: missing the <!-- ... --> header block')
    meta = {}
    for line in match.group(1).splitlines():
        key, _, value = line.partition(':')
        meta[key.strip()] = value.strip()
    for key in ('path', 'page', 'title', 'description'):
        if key not in meta:
            raise SystemExit(f'{path}: header block is missing "{key}:"')
    return meta, text[match.end():]


def build():
    layout = (SRC / 'layout.html').read_text(encoding='utf-8')
    if layout.count('{{main}}') != 1:
        raise SystemExit('src/layout.html must contain {{main}} exactly once')

    for source in sorted((SRC / 'pages').glob('*.html')):
        meta, body = read_page(source)
        out_dir = meta['path'].strip('/')
        root = '../' * len(out_dir.split('/')) if out_dir else './'

        html = layout.replace('{{main}}', body.rstrip('\n'))
        for key, value in (('root', root), ('page', meta['page']),
                           ('title', meta['title']), ('description', meta['description'])):
            html = html.replace('{{%s}}' % key, value)
        if meta.get('nav'):
            html = html.replace(f'data-nav="{meta["nav"]}"', f'data-nav="{meta["nav"]}" aria-current="page"')

        leftover = re.findall(r'\{\{\w+\}\}', html)
        if leftover:
            raise SystemExit(f'{source}: unknown placeholder(s) {sorted(set(leftover))}')

        note = (f'<!-- Generated by build.py from src/pages/{source.name} and src/layout.html.'
                ' Edit those files, then run: python3 build.py -->')
        html = html.replace('<!doctype html>', f'<!doctype html>\n{note}', 1)

        target = SITE / out_dir / 'index.html' if out_dir else SITE / 'index.html'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(html, encoding='utf-8')
        print(f'{source.name:16} -> {target.relative_to(SITE)}')


if __name__ == '__main__':
    build()
